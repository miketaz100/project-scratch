"""
gen_s0_stl.py - STL generator for every printed S0 part (PROJECT SCRATCH, 14-build/S0/cad, 2026-10-02)

THE .scad FILES ARE THE SOURCE OF TRUTH for the hand-written geometry; this script rebuilds the
same solids with manifold3d (no OpenSCAD binary on the build machine) and exports STL via trimesh.
Constant names match s0_lib.scad.  Two inputs are GENERATED by dish_kinematics.py and shared by
both: pocket_mesh.json / pocket_cavity.scad (dish pocket) and dish_geometry.json /
template_paths.scad (template stylus paths).  Run dish_kinematics.py first.

Each part is modelled in its working frame (dish parts: C = ball centre at the origin, +Z up the
pad axis) and then turned into its PRINT orientation and dropped onto z = 0 before export, so every
STL opens ready to slice.  README.md gives material, layer, infill and print-service notes.

Run:   <cadenv>/bin/python gen_s0_stl.py         exit code 0 only if every STL is watertight
"""
