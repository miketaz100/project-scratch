DENS = {"PLA": 1.24, "PETG": 1.27, "resin": 1.15}

def main(argv):
    only = None
    for a in argv:
        if a.startswith("--only="):
            only = set(a.split("=", 1)[1].split(","))
    rows, fails = [], 0
    for fname, builder, rot, mat, qty, note in build_parts():
        if only and not any(fname.startswith(o) for o in only):
            continue
        try:
            m = builder()
        except Exception as e:
            print(f"{fname}: BUILD ERROR {e!r}")
            fails += 1
            continue
        if fname == "D14_side_mock_70x150":
            m = to_bed(m)            # skirt edges on the bed, dome up (no supports)
        else:
            m = to_bed(m, rot)
        tm = to_trimesh(m)
        tm.export(os.path.join(OUT, fname + ".stl"))
        bb = m.bounding_box()
        size = [bb[i + 3] - bb[i] for i in range(3)]
        comps = [c for c in m.decompose() if c.volume() > 0]
        wt = bool(tm.is_watertight and tm.is_volume and len(comps) == 1 and m.status() == m3.Error.NoError)
        vol = m.volume() / 1000.0
        dens = DENS["resin"] if mat.startswith("resin") else DENS["PETG"] if mat.startswith("PETG") else DENS["PLA"]
        rows.append((fname, size, vol, vol * dens, wt, qty, mat, len(comps)))
        if not wt:
            fails += 1
    print(f"\n{'file':34s} {'bbox X x Y x Z (mm)':24s} {'cm3':>7s} {'g solid':>8s} {'qty':>3s} {'watertight':10s} material")
    for fname, size, vol, g, wt, qty, mat, nc in rows:
        print(f"{fname:34s} {size[0]:6.1f} x {size[1]:6.1f} x {size[2]:6.1f} {vol:7.1f} {g:8.1f} {qty:3d} {'yes' if wt else 'NO (%d parts)' % nc:10s} {mat}")
    print(f"\n{sum(1 for r in rows if r[4])}/{len(rows)} watertight")
    return 1 if fails else 0

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
