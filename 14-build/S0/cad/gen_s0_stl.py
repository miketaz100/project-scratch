def drum():
    z_f1 = HUB_H
    z_ga = z_f1 + FL_H
    z_sep = z_ga + GROOVE_W
    z_gb = z_sep + SEP_W
    z_f2 = z_gb + GROOVE_W
    z_top = z_f2 + FL_H
    solid = U(cyl(HUB_D, 0, z_f1 + 0.01), cyl(DRUM_FL_D, z_f1, z_ga), cyl(DRUM_LAND_D, z_ga - 0.01, z_f2 + 0.01),
              cyl(DRUM_FL_D, z_f2, z_top))
    cuts = []
    turns = GROOVE_W / GROOVE_PITCH
    for z0 in (z_ga, z_gb):
        cs = CrossSection.circle(GROOVE_R, 16).translate([DRUM_PITCH_D / 2, 0])
        cuts.append(Manifold.extrude(cs, GROOVE_W, int(turns * 48), -360.0 * turns).translate([0, 0, z0]))
    bore = D(cyl(SHAFT_D, -1, z_top + 1, fn=40), box(SHAFT_FLAT, 5, -5, 5, -2, z_top + 2))
    cuts.append(bore)
    cuts.append(cyl_axis(3.2, (0, 0, HUB_H / 2), (HUB_D / 2 + 1, 0, HUB_H / 2), fn=20))      # M3 grub screw onto the flat
    cuts.append(box(3.4, 6.0, -2.95, 2.95, -1.0, HUB_H / 2 + 2.95))                          # M3 nut slot, open to the motor face
    # cable anchors: groove end -> radial channel on the flange's inner face -> axial hole at
    # ANCHOR_R -> crimp sleeve pocket on the flange's outer face (outside the hub on the motor side)
    cuts.append(box(DRUM_PITCH_D / 2 - 0.4, ANCHOR_R + 0.5, -0.5, 0.5, z_ga - 1.0, z_ga + 0.01))
    cuts.append(cyl(1.0, z_f1 - 0.5, z_ga + 0.5, ANCHOR_R, 0, fn=16))
    cuts.append(box(ANCHOR_R - 1.0, DRUM_FL_D / 2 + 1, -1.1, 1.1, z_f1 - 0.01, z_f1 + 1.2))
