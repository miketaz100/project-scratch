def side_mock():
    """70 x 150 side-of-head mock: torus patch, tube radius 70 (crosswise), outer radius 150
    (lengthwise), 2.4 mm shell with a perimeter skirt, top point at z = 150 before dropping to bed."""
    def torus(r_tube):
        prof = [(80.0 + r_tube * math.cos(a), r_tube * math.sin(a)) for a in np.linspace(0, 2 * math.pi, 160, endpoint=False)]
        return Manifold.revolve(CrossSection([prof]), 220).rotate([0, 90, 0])     # axis along X
    half = 62.0
    outer = torus(70.0) ^ box(-half, half, -half, half, 108.0, 160.0)
    inner = torus(67.6) ^ box(-half + 2.4, half - 2.4, -half + 2.4, half - 2.4, 100.0, 160.0)
    return outer - inner

def lift_gauge():
    parts = [box(0, 12, 0, 10, 0, 2.0)]                                           # 2.0 mm reserve tab
    for i, h in enumerate((3.0, 4.0, 5.0, 6.0, 7.0)):
        parts.append(box(12 + 12 * i, 24 + 12 * i, 0, 10, 0, h))
    g = U(*parts)
    cuts = [box(14 + 12 * i, 14.8 + 12 * i, 7.0, 10.5, h - 0.4, h + 1) for i, h in enumerate((3.0, 4.0, 5.0, 6.0, 7.0)) for _ in range(1)]
    return D(g, *cuts)

